import 'dart:io';
import 'package:ffigen/ffigen.dart';

/// Run with the isolated tool/ffigen package configuration; see its README.
Future<void> main() async {
  final root = Platform.script.resolve('../../');
  final sdk = Directory(
    Platform.environment['WINDOWS_SDK_INCLUDE'] ??
        'C:/Program Files (x86)/Windows Kits/10/Include/10.0.26100.0',
  );
  final output = root.resolve('lib/src/third_party/');
  await FfiGenerator(
    input: Input(
      entryPoints: [sdk.uri.resolve('um/Windows.h')],
      compilerOptions: [
        '--target=x86_64-pc-windows-msvc',
        '-fms-extensions',
        '-D_WIN32_WINNT=0x0601',
        '-DWIN32_LEAN_AND_MEAN',
        // Ignore unrelated SDK intrinsic/packing warnings; parse errors stay fatal.
        '-Wno-everything',
        '-I${Platform.environment['VCTOOLS_INCLUDE'] ?? 'C:/Program Files/Microsoft Visual Studio/2022/Community/VC/Tools/MSVC/14.44.35207/include'}',
        for (final folder in ['um', 'shared', 'ucrt', 'winrt'])
          '-I${sdk.path}/$folder',
      ],
    ),
    visitors: [
      Visitor(
        func: (node) {
          node.isIncluded = {
            'GetCurrentProcess',
            'GetProcessTimes',
          }.contains(node.originalName);
          node.isLeaf = node.isIncluded;
          // System DLL lookup is not a native asset. Dart rejects RecordUse on
          // ffigen 23 dynamic instance methods; no tree-shaking map is needed.
        },
        struct: (node) {
          if (node.originalName == '_FILETIME') {
            node.isIncluded = true;
            node.name = 'FileTime';
          }
        },
      ),
    ],
    output: Output(
      dart: DartOutput(path: output.resolve('windows_process.g.dart')),
      style: const DynamicLibraryBindings(wrapperName: 'WindowsProcess'),
      preamble: '''// Generated by package:ffigen 23.0.0. Do not edit manually.
// Windows SDK processthreadsapi.h and minwindef.h declarations:
// Copyright (c) Microsoft Corporation. All rights reserved.
// Generated interop code is distributed under this repository's MIT license.
// ignore_for_file: non_constant_identifier_names, camel_case_types
''',
    ),
  ).generate(
    libclangDylib: Uri.file(
      Platform.environment['LIBCLANG_PATH'] ??
          'C:/msys64/ucrt64/bin/libclang.dll',
    ),
  );
}
